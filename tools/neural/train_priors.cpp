// Generates src/Cafe/HW/Espresso/Recompiler/Neural/NeuroJitDefaultWeights.h
//
// The built-in weights are PRIORS: a cost model trained on a synthetic workload (tests/neural/NeuroJitSynthetic.h, regime
// Baseline) so the model starts with sane behaviour (bigger/more complex function = more expensive). They are NOT trained on real
// games. On the device the model keeps learning from the real compile times; the trace file it writes (neural/jit_cost_trace.csv)
// can be used to retrain real weights with this same tool (see tools/neural/README.md).
//
// build & run (from the repository root), two commands:
//   g++ -std=c++20 -O2 -Isrc -Itests/neural tools/neural/train_priors.cpp -o /tmp/train_priors
//   /tmp/train_priors src/Cafe/HW/Espresso/Recompiler/Neural/NeuroJitDefaultWeights.h [trace.csv]
#include "Cafe/HW/Espresso/Recompiler/Neural/NeuralMLP.h"
#include "Cafe/HW/Espresso/Recompiler/Neural/NeuroJitFeatures.h"
#include "NeuroJitSynthetic.h"
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

struct Sample { NeuroJit::CodeFeatures f; float logMs; };

static std::vector<Sample> LoadTrace(const char* path)
{
	std::vector<Sample> out;
	std::ifstream in(path);
	std::string line;
	std::getline(in, line); // header: addr,words,cond,uncond,calls,back,fp,load,store,indirect,blr,span,alu,ms,pred_ms
	while (std::getline(in, line))
	{
		std::stringstream ss(line);
		std::string tok;
		std::vector<double> v;
		while (std::getline(ss, tok, ','))
			v.push_back(std::atof(tok.c_str()));
		if (v.size() < 15 || !(v[13] > 0.0))
			continue;
		Sample s;
		for (int i = 0; i < NeuroJit::kFeatureCount; i++)
			s.f.v[i] = (float)v[1 + i];
		s.f.valid = true;
		s.logMs = std::log((float)v[13]);
		out.push_back(s);
	}
	return out;
}

int main(int argc, char** argv)
{
	if (argc < 2)
	{
		std::fprintf(stderr, "usage: train_priors <output.h> [trace.csv]\n");
		return 2;
	}
	std::vector<Sample> data;
	if (argc >= 3)
	{
		data = LoadTrace(argv[2]);
		std::printf("loaded %zu real samples from %s\n", data.size(), argv[2]);
	}
	if (data.empty())
	{
		Neural::Rng rng(12345);
		for (int i = 0; i < 40000; i++)
		{
			Sample s;
			s.f = NeuroJitSynth::RandomFeatures(rng);
			s.logMs = std::log(NeuroJitSynth::MeasuredMs(s.f, NeuroJitSynth::Regime::Baseline, rng));
			data.push_back(s);
		}
		std::printf("using %zu synthetic samples (regime Baseline)\n", data.size());
	}
	Neural::MLP m;
	const int dims[4] = { NeuroJit::kFeatureCount, 16, 8, 1 };
	m.Init(dims, 3);
	m.InitRandom(2024);
	Neural::Rng order(7);
	const int epochs = 30;
	for (int e = 0; e < epochs; e++)
	{
		const float lr = 0.02f / (1.0f + 0.15f * e);
		double lossSum = 0;
		for (size_t k = 0; k < data.size(); k++)
		{
			const Sample& s = data[order.NextU64() % data.size()];
			float x[NeuroJit::kFeatureCount];
			NeuroJit::NormalizeFeatures(s.f, x);
			const float t = s.logMs;
			lossSum += m.TrainStep(x, &t, lr, 1.0f, 5.0f, 1e-6f);
		}
		if (e % 5 == 4 || e == epochs - 1)
			std::printf("epoch %2d  mean loss %.4f\n", e + 1, lossSum / data.size());
	}
	double mae = 0;
	for (size_t k = 0; k < data.size(); k++)
	{
		float x[NeuroJit::kFeatureCount], o[1];
		NeuroJit::NormalizeFeatures(data[k].f, x);
		m.Forward(x, o);
		mae += std::fabs(o[0] - data[k].logMs);
	}
	std::printf("final MAE (ln ms): %.4f  heuristic-only MAE would be ", mae / data.size());
	double hm = 0;
	for (auto& s : data) hm += std::fabs(NeuroJit::HeuristicLogMs(s.f) - s.logMs);
	std::printf("%.4f\n", hm / data.size());

	std::vector<uint8_t> blob(m.SerializedSize());
	if (!m.Serialize(blob.data(), blob.size(), 0x4354494Au))
		return 1;
	FILE* fp = std::fopen(argv[1], "w");
	if (!fp) return 1;
	std::fprintf(fp, "#pragma once\n// GENERATED by tools/neural/train_priors.cpp - do not edit by hand.\n// Priors (see that file): synthetic Baseline workload unless a real trace was given.\n#include <cstddef>\n#include <cstdint>\n\nnamespace NeuroJit\n{\n\tinline constexpr uint8_t kDefaultWeights[%zu] = {", blob.size());
	for (size_t i = 0; i < blob.size(); i++)
		std::fprintf(fp, "%s0x%02X,", (i % 16 == 0) ? "\n\t\t" : " ", blob[i]);
	std::fprintf(fp, "\n\t};\n\tinline constexpr size_t kDefaultWeightsSize = %zu;\n}\n", blob.size());
	std::fclose(fp);
	std::printf("wrote %s (%zu bytes of weights)\n", argv[1], blob.size());
	return 0;
}
